function makeTemplates(groupId, title, intent, count, length) {
  const pool = TEXT_POOLS[groupId] || TEXT_POOLS.fallback_unknown;
  const closers = ['', ' إذا بدك، أعطني تفصيلا واحدا أكثر.', ' أقدر أختصرها أكثر لو السؤال صغير.', ' خلينا نخليها واضحة ومباشرة.'];
  return Array.from({ length: count }, (_, index) => {
    const base = pool[index % pool.length];
    const suffix = index >= pool.length ? closers[index % closers.length] : '';
    return {
      id: `${groupId}_${String(index + 1).padStart(3, '0')}`,
      intent,
      tone: intent === 'unsafe_or_sensitive' ? 'safe' : 'friendly',
      length,
      priority: Math.max(1, 10 - Math.floor(index / 10)),
      triggers: TRIGGERS[intent] || TRIGGERS[groupId] || [],
      text: `${base}${suffix}`
    };
  });
}

