function words(value) {
  return String(value || '')
    .split(/\s+/)
    .map(word => word.trim())
    .filter(Boolean)
    .slice(0, 5);
}

function entry(category, index, title, tags, content, useWhen = []) {
  return {
    id: `${category}_${String(index + 1).padStart(3, '0')}`,
    category,
    tags: [...new Set([...tags, ...words(title)])],
    priority: Math.max(4, 10 - Math.floor(index / 7)),
    title,
    content,
    useWhen
  };
}

function makeEntries(category, items, template) {
  return items.map((item, index) => entry(
    category,
    index,
    item.title,
    item.tags || [],
    item.content || template(item, index),
    item.useWhen || []
  ));
}

